# v056: smoke test of the Dream (the upgrade screen): opens it at several moments of the game, buys through it, checks the
# visibility rules and the camera, and writes screenshots (SHOT folder, default /tmp). Run after build:  python3 -u test_traum.py
import asyncio, glob, re, os, sys
from playwright.async_api import async_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
FILE = max(glob.glob(os.path.join(HERE, '..', 'robinson_v*.html')), key=lambda f: int(re.findall(r'v(\d+)', f)[-1]))
SHOT = os.environ.get('SHOT', '/tmp')
FAIL = []
def check(ok, what):
    print(('  ok   ' if ok else '  FAIL ') + what)
    if not ok: FAIL.append(what)

VIS = "Array.from(document.querySelectorAll('#traum .tb')).map(g => g.dataset.id)"
LBL = "Array.from(document.querySelectorAll('#traum .tb text')).map(t => t.textContent + ':' + t.getAttribute('fill'))"

async def main():
    print('file:', FILE.split('/')[-1])
    async with async_playwright() as p:
        br = await p.chromium.launch()
        for vw, vh, tag in [(1280, 720, 'wide'), (390, 844, 'phone')]:
            pg = await br.new_page(viewport={'width': vw, 'height': vh})
            errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
            await pg.goto('file://' + FILE); await pg.wait_for_timeout(1200)
            await pg.evaluate("localStorage.removeItem('robinson_save_v1')")
            csv = open(os.path.join(HERE, 'test_save_t29.csv')).read()
            print(f'[{tag}] 1 · beach only, early: the stamp and the board')
            await pg.evaluate("p => SPIEL.laden(SPIEL.RSAVE.pick(p, 'game').st)", csv); await pg.wait_for_timeout(2500)
            # an early beach: no island, stage 3, only the stamp upgrades bought
            await pg.evaluate("""(() => { const S = STRAND.S; Object.keys(S.upg).forEach(k => S.upg[k] = 0); S.upg.jump = 1; S.upg.speed = 2; S.flood = 3; S.green = 300; S.tails = 0; S.seen.fish = false; S.traumSeen = {}; })()""")
            await pg.evaluate("INSEL.G.unl = {}; INSEL.G.friends.banyan = false; INSEL.G.caseFound = false")
            ok = await pg.evaluate("SPIEL.traum()"); await pg.wait_for_timeout(3500)
            check(ok and await pg.evaluate("TRAUM.offen"), 'the Dream opens')
            v = await pg.evaluate(VIS)
            check('jump' in v and 'speed' in v and 'boostLen' in v and 'void' not in v and 'catDive' not in v and 'listen' not in v and 'cycle' not in v, f'early: board + stamp only ({v})')
            l = await pg.evaluate(LBL)
            check(any(x.startswith('Faster Stamping') for x in l) and not any(x.startswith('Jump') for x in l), f'names only on what is buyable ({l})')
            check(any(x.startswith('Heavier Stamp') and x.endswith('#ff5a5a') for x in l) is False, 'Heavier Stamp (80) affordable with 300 → not red')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_1.png')
            # select and buy through the detail column
            await pg.evaluate("document.querySelector('#traum .tb[data-id=\"speed\"]').dispatchEvent(new MouseEvent('click', { bubbles: true }))"); await pg.wait_for_timeout(300)
            t = await pg.evaluate("document.querySelector('#traum .tpanel').innerText")
            check('Faster Stamping' in t and 'Level 2 / 6' in t, f'detail column shows the upgrade ({t[:80]!r})')
            g0 = await pg.evaluate("STRAND.S.green"); await pg.evaluate("document.querySelector('#traum .tbuy').click()"); await pg.wait_for_timeout(300)
            check(await pg.evaluate("STRAND.S.upg.speed === 3") and await pg.evaluate("STRAND.S.green") < g0, 'buying in the Dream pays and levels up')
            await pg.evaluate("STRAND.S.green = 10"); await pg.evaluate("TRAUM.zu(); SPIEL.traum()"); await pg.wait_for_timeout(600)
            l = await pg.evaluate(LBL)
            check(all(x.endswith('#ff5a5a') for x in l) and len(l) > 0, f'too dear → red names ({l})')
            await pg.evaluate("TRAUM.zu()")
            print(f'[{tag}] 2 · stage 8, fish, VOID: the cat islet and the tortoise')
            await pg.evaluate("(() => { const S = STRAND.S; S.flood = 8; S.upg.cycle = 1; S.seen.fish = true; S.tails = 9; S.rum = 9; S.green = 5000; })()")
            await pg.evaluate("SPIEL.traum()"); await pg.wait_for_timeout(3500)
            v = await pg.evaluate(VIS)
            check(all(k in v for k in ['cycle', 'cycleBoom', 'void', 'catDive', 'lapcat']) and 'catBoard' not in v and 'voidCharge' not in v, f'stage 8: Wall Leap, VOID, the cat ({v})')
            n = await pg.evaluate("Object.keys(STRAND.S.traumSeen).filter(k => !k.startsWith('g_') && !k.startsWith('t_') && k !== '_intro').length")
            check(n == len(v), f'everything shown is marked seen ({n}/{len(v)})')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_2.png')
            await pg.evaluate("TRAUM.zu()")
            print(f'[{tag}] 3 · the banyan: Listen, then its branches; the clouds part')
            await pg.evaluate("INSEL.G.friends.banyan = true; INSEL.G.wFree = 30")
            await pg.evaluate("SPIEL.traum()"); await pg.wait_for_timeout(1200)
            v = await pg.evaluate(VIS)
            check('listen' in v and 'coarse' not in v, f'Listen shows once the banyan is a friend ({v[-3:]})')
            await pg.evaluate("document.querySelector('#traum .tb[data-id=\"listen\"]').dispatchEvent(new MouseEvent('click', { bubbles: true }))"); await pg.wait_for_timeout(200)
            await pg.evaluate("document.querySelector('#traum .tbuy').click()"); await pg.wait_for_timeout(3500)
            v = await pg.evaluate(VIS)
            check(await pg.evaluate("!!INSEL.G.unl.listen") and all(k in v for k in ['coarse', 'rootOrder', 'tower', 'cleanRot', 'ableger']) and 'fine' not in v and 'deepRoots' not in v, f'after Listen: Sap, Roots and Orders (picture hierarchy) ({v})')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_3.png')
            await pg.evaluate("TRAUM.zu()")
            print(f'[{tag}] 4 · the briefcase: the secret at the tip, the full mirror')
            await pg.evaluate("INSEL.G.caseFound = true; INSEL.G.fiWipe = INSEL.G.fiWipe === undefined ? 1 : INSEL.G.fiWipe; INSEL.G.wFree = 60")
            await pg.evaluate("SPIEL.traum()"); await pg.wait_for_timeout(4200)
            v = await pg.evaluate(VIS)
            check('elf' in v, f'the Dark-Wood Elf shows with the briefcase')
            cam = await pg.evaluate("document.querySelector('#traum .twelt').style.transform")
            check('scale' in cam, f'camera set ({cam})')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_4.png')
            print(f'[{tag}] 5 · the cat has left: her islet empties, her upgrades go')
            await pg.evaluate("TRAUM.zu(); STRAND.S.katzeWeg = true; SPIEL.traum()"); await pg.wait_for_timeout(3000)
            v = await pg.evaluate(VIS)
            check(not any(k in v for k in ['catDive', 'lapcat']), 'no cat upgrades once she has left')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_5.png')
            await pg.evaluate("TRAUM.zu(); STRAND.S.katzeWeg = false")
            print(f'[{tag}] 6 · the banyan screen: sap flow first, the way into the Dream')
            await pg.evaluate("SPIEL.zeige('insel', { force: true })"); await pg.wait_for_timeout(800)
            await pg.evaluate("INSEL.openTree()"); await pg.wait_for_timeout(600)
            h = await pg.evaluate("document.querySelector('#insel #tDreamHint').innerText")
            check(len(h) > 10 and not await pg.evaluate("!!document.querySelector('#insel #tCv')"), f'banyan screen: hint, no old tree ({h!r})')
            await pg.screenshot(path=f'{SHOT}/traum_{tag}_6.png')
            await pg.evaluate("document.querySelector('#insel #tDream').click()"); await pg.wait_for_timeout(500)
            check(await pg.evaluate("TRAUM.offen"), 'the Dream button in the banyan screen opens the Dream')
            await pg.evaluate("TRAUM.zu()"); await pg.wait_for_timeout(300)
            check(await pg.evaluate("document.querySelector('#insel #treeScr').style.display") == 'flex', 'closing the Dream lands back in the banyan screen')
            check(not errs, f'no page errors ({errs[:3]})')
            await pg.close()
        await br.close()
    print('RESULT:', 'all ok' if not FAIL else f'{len(FAIL)} failed'); sys.exit(1 if FAIL else 0)
asyncio.run(main())
